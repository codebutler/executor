/* State 0 (Silver) role → palette index. */
constexpr int kActiveRoles[17] = {
    7, 0, 0, 10, 4, 4, 10, 10, 2, -1, -1, -1, -1, -1, 10, 2, 5
};

inline void role_rgb(int role, uint8_t *r, uint8_t *g, uint8_t *b)
{
    int idx = (role >= 0 && role < 17) ? kActiveRoles[role] : 0;
    if(idx < 0 || idx > 13)
        idx = 0;
    *r = kPalette[idx][0];
    *g = kPalette[idx][1];
    *b = kPalette[idx][2];
}

