/* CDEF 23 check/radio — linear grayscale nibble N → N×0x11 */
inline void cdef23_linear_clut(RGBColor out[16])
{
    for(int i = 0; i < 16; ++i)
    {
        uint8_t v = (uint8_t)(i * 0x11);
        out[i].red = out[i].green = out[i].blue =
            (unsigned short)((v << 8) | v);
    }
}

